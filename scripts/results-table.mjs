#!/usr/bin/env node
// Builds the README "Results" table from a ghost gate CSV: one row per condition with
// denominators, then the ratio, pair wins, sanity check and verdict under the same rule as
// scripts/trials-verdict.mjs. Prints the markdown and writes it to docs/results/ghost-gate.md
// with the CSV's name and SHA-256. Never writes README.md: the table is pasted there by hand
// after the real sitting.
// Usage: node scripts/results-table.mjs <csv>
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { COLUMNS, PASS_RULE_TEXT, caption, checkHeader, fmtP, fmtS, parseCsv, readTrials, summarize } from './lib/gate.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'docs', 'results', 'ghost-gate.md');

const file = process.argv[2];
if (!file) {
  console.error('usage: node scripts/results-table.mjs <csv>');
  process.exit(2);
}

let text;
try {
  text = readFileSync(file, 'utf8');
} catch (err) {
  console.error(`cannot read ${file}: ${err instanceof Error ? err.message : String(err)}`);
  process.exit(2);
}

const header = parseCsv(text)[0] ?? [];
const headerCheck = checkHeader(header);
if (!headerCheck.ok) {
  console.error(`Header check: FAIL: ${headerCheck.problems.join('; ')}`);
  process.exit(2);
}

let parsed;
try {
  parsed = readTrials(text);
} catch (err) {
  console.error(`cannot score ${file}: ${err instanceof Error ? err.message : String(err)}`);
  process.exit(2);
}
const s = summarize(parsed.trials);
if (s.on.n === 0 || s.off.n === 0) {
  console.error(`cannot score ${file}: ${s.on.n} counted ghost_on and ${s.off.n} counted ghost_off trials (both must be above 0)`);
  process.exit(2);
}

const sec = (v) => (v === null ? 'n/a' : v === Infinity ? 'not reached' : v.toFixed(2));
const row = (label, c) =>
  `| ${label} | ${c.n} | ${c.successes}/${c.n} | ${sec(c.medianCompletion)} | ${sec(c.medianReach)} (n=${c.reachN}) | ${sec(c.medianGrasp)} (n=${c.graspN}) |`;
const delay = (c) => {
  const ms = c.delaysMs.filter((v) => v !== null);
  if (ms.length === 0) return 'delay not logged';
  if (ms.length > 1) return `delay ${ms.map((v) => `${v}`).join('/')} ms one way (mixed)`;
  return ms[0] === 0 ? 'no delay' : `delay ${((2 * ms[0]) / 1000).toFixed(2)} s round trip`;
};
const ratio = s.rule.ratio === null ? 'undefined' : s.rule.ratio === Infinity ? 'not reached' : s.rule.ratio.toFixed(2);

const table = [
  '| Condition | Trials | Successes | Median completion (s) | Median reach (s) | Median grasp (s) |',
  '|---|---|---|---|---|---|',
  row(`Direct, ${delay(s.direct)} (warm-ups)`, s.direct),
  row(`Moon, ${delay(s.off)}, ghost off`, s.off),
  row(`Moon, ${delay(s.on)}, ghost on`, s.on),
  '',
  `*${caption(s)}.* Completion is GO to a stable lift on the true arm; a failure (no stable lift before the cutoff) counts as slowest in the median. ` +
    'Reach and grasp medians are over successful trials.',
  '',
  `Ratio median(on) / median(off): ${ratio}. Pair wins with the ghost: ${s.pairs.wins} of ${s.pairs.wins + s.pairs.losses} ` +
    `(exact sign-test p = ${fmtP(s.pairs.p)}; weak evidence at this size). Sanity check: ${s.sanity.status}. Verdict: **${s.rule.verdict}** (${s.rule.reason}).`,
].join('\n');

const hash = createHash('sha256').update(text).digest('hex').slice(0, 16);
const doc = [
  '# Ghost gate results',
  '',
  `Generated by \`node scripts/results-table.mjs\` from \`${path.basename(file)}\` (SHA-256 ${hash}...), ` +
    `${s.total} rows, header ${COLUMNS.length} columns in the logged order.`,
  s.gateData ? '' : '\n**Not gate data.** These rows are not all operator=ahmed with input_source=webcam, so they do not decide anything.\n',
  table,
  '',
  '## Pass rule (fixed before any trial)',
  '',
  PASS_RULE_TEXT,
  '',
].join('\n');

mkdirSync(path.dirname(OUT), { recursive: true });
writeFileSync(OUT, doc);

console.log(`Header check: ${COLUMNS.length} columns in the logged order: OK`);
console.log(table);
console.log(`\nWrote ${path.relative(ROOT, OUT).split(path.sep).join('/')}`);
