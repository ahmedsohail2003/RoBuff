// Writes a JSON gallery of 12 generated objects with their receipts and settle reports,
// and an OBJ of one asteroid, so a person can look at the shapes.
// Usage (from web/): node scripts/run-ts.mjs scripts/gallery.ts [output-dir]
// Default output: the git-ignored private evidence folder at the repo root.

import loadMujoco from '@mujoco/mujoco';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { GALLERY_SPECS } from '../src/objects/gallery';
import { validate } from '../src/objects/guardrail';
import { toMjcf } from '../src/objects/mjcf';
import { meshToObj } from '../src/objects/obj';
import { receiptSummary } from '../src/objects/receipt';
import { settle, withSettle } from '../src/objects/settle';

const here = dirname(fileURLToPath(import.meta.url));
const outDir = resolve(process.argv[2] ?? join(here, '..', '..', 'private', '.autopilot', 'evidence'));
mkdirSync(outDir, { recursive: true });

const mj = await loadMujoco();
const objects = [];
const compileMs: number[] = [];
let largestRoll = 0;

for (const { label, spec, options } of GALLERY_SPECS) {
  // Refused objects that still have a safe hull (SLIPS, TOO_HEAVY) are settled too, to show what would happen.
  let receipt = validate(spec, options);
  let report = null;
  if (receipt.hull) {
    report = settle(mj, receipt);
    receipt = withSettle(receipt, report);
    compileMs.push(report.compile_ms);
    largestRoll = Math.max(largestRoll, report.rolled_mm);
  }
  objects.push({
    label,
    spec,
    options: options ?? {},
    verdict: receipt.verdict,
    lines: receipt.steps.map((s) => `${s.code}: ${s.message}`),
    receipt: receiptSummary(receipt),
    settle: report,
    mjcf_chars: receipt.hull ? toMjcf(receipt).asset.length + toMjcf(receipt).body.length : null,
  });
  console.log(`${label.padEnd(40)} ${receipt.verdict.padEnd(20)} ${receipt.mass_kg === null ? '' : `${(receipt.mass_kg * 1000).toFixed(1)} g`}  ${report ? `compile ${report.compile_ms.toFixed(1)} ms, rolled ${report.rolled_mm.toFixed(2)} mm, ${report.step.code}` : ''}`);
}

const sorted = compileMs.slice().sort((a, b) => a - b);
const mid = Math.floor(sorted.length / 2);
const median = sorted.length % 2 ? sorted[mid]! : (sorted[mid - 1]! + sorted[mid]!) / 2;
const gallery = {
  generated_at: new Date().toISOString(),
  generator: 'web/scripts/gallery.ts',
  honesty: 'Simulated only. Receipts come from the cheap guardrail plus a MuJoCo settle on a plane at Earth gravity. The arm lift test has not been run on any of these, so none reads PASS. A real arm is unverified.',
  mujoco: '@mujoco/mujoco 4.0.0 WASM in Node',
  median_compile_ms: median,
  largest_rolled_mm: largestRoll,
  objects,
};
const jsonPath = join(outDir, 's4-gallery.json');
writeFileSync(jsonPath, `${JSON.stringify(gallery, null, 2)}\n`);

const asteroid = validate(GALLERY_SPECS[0]!.spec);
const objPath = join(outDir, 's4-asteroid.obj');
writeFileSync(objPath, meshToObj(asteroid.mesh!, `${GALLERY_SPECS[0]!.label}, seed ${asteroid.spec.seed}\ngenerated by web/src/objects, ${asteroid.mesh!.positions.length / 3} vertices`));

console.log(`median compile ${median.toFixed(1)} ms, largest rolled ${largestRoll.toFixed(2)} mm`);
console.log(`wrote ${jsonPath}`);
console.log(`wrote ${objPath}`);
